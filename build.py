#!/usr/bin/env python3
"""Build Markdown posts using Pandoc; run with --help for usage."""
import argparse
from datetime import date
from html import escape
import json
from pathlib import Path
import re
import shutil
from string import Template
import subprocess
import sys

ROOT = Path(__file__).resolve().parent
MARKER = '<!-- Generated by build.py; edit the Markdown source or template instead. -->'
READER = 'markdown-smart'  # Preserve the author's punctuation.


def pandoc(text, *args):
    result = subprocess.run(
        ['pandoc', *args], input=text, text=True, encoding='utf-8',
        stdout=subprocess.PIPE, stderr=subprocess.PIPE,
    )
    if result.returncode:
        raise ValueError(result.stderr.strip())
    return result.stdout


def plain(node):
    """Read plain text from Pandoc metadata while retaining inline formatting text."""
    if isinstance(node, list):
        return ''.join(plain(item) for item in node)
    if not isinstance(node, dict) or 't' not in node:
        return ''
    kind, content = node['t'], node.get('c')
    if kind in ('Str', 'MetaString'):
        return content
    if kind in ('Space', 'SoftBreak', 'LineBreak'):
        return ' '
    if kind in ('Code', 'Math'):
        return content[1]
    if kind in ('Link', 'Image', 'Span'):
        return plain(content[1])
    if kind in ('Quoted', 'Cite'):
        return plain(content[1])
    return plain(content)


def has_math(node):
    if isinstance(node, dict):
        return node.get('t') == 'Math' or any(has_math(v) for v in node.values())
    return isinstance(node, list) and any(has_math(v) for v in node)


def flag(meta, key, default=False):
    if key not in meta:
        return default
    if meta[key]['t'] != 'MetaBool':
        raise ValueError(f'{key} must be true or false (without quotes)')
    return meta[key]['c']


def pretty_date(value):
    return f'{value.day} {value.strftime("%B")} {value.year}'


def render(template, title, body, prefix='', math=False, blog=False, description=''):
    return MARKER + '\n' + template.substitute(
        title=escape(title, quote=True), description=escape(description or title, quote=True),
        body=body, prefix=prefix,
        blog_current=' aria-current="page"' if blog else '',
        math_scripts=(f'<script defer src="{prefix}math-config.js"></script>\n'
                      f'<script defer src="{prefix}assets/mathjax/tex-svg.js"></script>') if math else '',
    )


def build():
    if not shutil.which('pandoc'):
        raise ValueError('Pandoc is required. Install it first: https://pandoc.org/installing.html')
    template = Template((ROOT / 'templates/page.html').read_text(encoding='utf-8'))
    outputs, posts = {}, []
    for source in sorted((ROOT / 'posts').glob('*/index.md')):
        try:
            doc = json.loads(pandoc(source.read_text(encoding='utf-8'), '-f', READER, '-t', 'json'))
            meta = doc['meta']
            if flag(meta, 'draft'):
                continue
            title = plain(meta.get('title', {})).strip()
            if not title:
                raise ValueError('a title is required in the YAML header')
            raw_date = plain(meta.get('date', {})).strip()
            if not re.fullmatch(r'\d{4}-\d{2}-\d{2}', raw_date):
                raise ValueError('date must be YYYY-MM-DD')
            published = date.fromisoformat(raw_date)
            author = plain(meta.get('author', {})).strip() or 'Laus Wullum'
            use_math = has_math(doc['blocks']) or flag(meta, 'math')
            # Pass only the body back to Pandoc; our template handles metadata.
            doc['meta'] = {}
            content = pandoc(json.dumps(doc), '-f', 'json', '-t', 'html5', '--wrap=none',
                             '--mathjax', '--no-highlight')
            content = (f'<article>\n<h1>{escape(title)}</h1>\n'
                       f'<p class="meta">{escape(author)} · '
                       f'<time datetime="{raw_date}">{pretty_date(published)}</time></p>\n'
                       f'<div class="post-body">\n{content}</div>\n'
                       '<p><a href="../../blogfront.html">← All posts</a></p>\n</article>')
            target = source.with_suffix('.html')
            if target.exists() and not target.read_text(encoding='utf-8').startswith(MARKER):
                raise ValueError('index.html was not generated by this script; move it aside before building')
            outputs[target] = render(template, title, content, prefix='../../', math=use_math)
            posts.append((published, source.parent.name, title))
        except (ValueError, KeyError) as error:
            raise ValueError(f'{source.relative_to(ROOT)}: {error}') from error
    listing = '<h1>Blog</h1>\n<ul class="post-list">\n'
    for published, slug, title in sorted(posts, key=lambda p: (-p[0].toordinal(), p[1])):
        from urllib.parse import quote
        listing += (f'<li><time datetime="{published.isoformat()}">{pretty_date(published)}</time>'
                    f'<a href="posts/{quote(slug, safe="")}/index.html">{escape(title)}</a></li>\n')
    listing += '</ul>\n' if posts else '</ul>\n<p>No posts yet.</p>\n'
    outputs[ROOT / 'blogfront.html'] = render(template, 'Blog', listing, blog=True)
    # Remove only files with our marker, so deleted/draft posts do not stay published.
    stale = [p for p in (ROOT / 'posts').glob('*/index.html')
             if p not in outputs and p.read_text(encoding='utf-8').startswith(MARKER)]
    # Everything is validated and rendered before making any changes.
    for target, content in outputs.items():
        target.write_text(content, encoding='utf-8')
    for target in stale:
        target.unlink()
        print(f'Removed generated page: {target.relative_to(ROOT)}')
    print(f'Built {len(posts)} post(s) and blogfront.html.')


def new_post(slug, title):
    if not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', slug):
        raise ValueError('Use a slug such as my-new-post (lowercase letters, digits, hyphens).')
    folder = ROOT / 'posts' / slug
    if folder.exists():
        raise ValueError(f'posts/{slug} already exists; nothing overwritten.')
    text = (ROOT / 'templates/post.md').read_text(encoding='utf-8')
    text = text.replace('"POST_TITLE"', json.dumps(title or slug.replace('-', ' ').capitalize(), ensure_ascii=False))
    text = text.replace('POST_DATE', date.today().isoformat())
    folder.mkdir(parents=True)
    (folder / 'index.md').write_text(text, encoding='utf-8')
    print(f'Created posts/{slug}/index.md. Edit it, then run: python3 build.py')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest='command')
    commands.add_parser('build', help='Build posts and update the blog listing (default).')
    new = commands.add_parser('new', help='Create a Markdown post without overwriting anything.')
    new.add_argument('slug', help='URL folder, e.g. my-new-post')
    new.add_argument('--title', help='Post title; defaults to the slug as words.')
    args = parser.parse_args()
    try:
        if args.command == 'new':
            new_post(args.slug, args.title)
        else:
            build()
    except (ValueError, OSError) as error:
        print(f'Error: {error}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
